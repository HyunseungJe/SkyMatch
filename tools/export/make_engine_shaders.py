"""Generates the Godot sky shader and the Unity skybox shader from the reference sky.

Usage: uv run tools/export/make_engine_shaders.py
Reads:  sky/skyV1.glsl (the sky; not edited), sky/sky_schema_v1.json (slider ranges, defaults, labels)
Writes: ports/godot/sky_match_v1.gdshader, ports/unity/SkyMatchV1/SkyMatchV1.shader, and a copy of
        sky/textures/noise256.png next to each (the tools need the texture inside their project)

Only mechanical, listed rewrites are applied; the sky math is copied unchanged. Re-run after
every change to sky/skyV1.glsl and commit the outputs with it.
"""
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GLSL = (ROOT / 'sky/skyV1.glsl').read_text(encoding='utf8')
SCHEMA = json.loads((ROOT / 'sky/sky_schema_v1.json').read_text(encoding='utf8'))
PARAMS = SCHEMA['params']

# The portable sky: from the first helper to the start of the web-only composer interface.
BODY = GLSL[GLSL.index('#define PI'):GLSL.index('// ---- Web composer interface')]
BODY = BODY.replace('#define PI 3.14159265359\n', '')
BODY = re.sub(r'struct Material \{[^}]*\};\n', '', BODY)
UNIFORMS = re.findall(r'^uniform\s+(float|int|vec3)\s+u_sky_(\w+)\s*=', GLSL, flags=re.M)
for _, name in UNIFORMS:
    if name not in PARAMS:
        raise SystemExit(f'GLSL uniform u_sky_{name} is not in the schema')

HEADER = (
    '// Sky Match sky v1 (schema {version}). GENERATED by tools/export/make_engine_shaders.py from\n'
    '// sky/skyV1.glsl; do not edit by hand. Input: unit view direction in sky space (Y up, north = +Z,\n'
    '// east = +X). Output: linear HDR radiance; exposure and tone mapping are the engine\'s job.\n'
    '// Colour parameters are entered as sRGB colours and reach the shader as linear values.\n'
    '// Contains code adapted from Felix Westin, "Fast semi-physical atmosphere" (MIT); notice below.\n'
).format(version=SCHEMA['version'])


def srgb(hex_):
    return [int(hex_[i:i + 2], 16) / 255 for i in (1, 3, 5)]


def num(x):
    return repr(float(x))


# ---- Godot 4 (shader_type sky) ----------------------------------------------
def godot():
    lines = []
    for glsl_type, name in UNIFORMS:
        p = PARAMS[name]
        if glsl_type == 'vec3':
            r, g, b = srgb(p['default'])
            lines.append(f'uniform vec3 u_sky_{name} : source_color = vec3({num(r)}, {num(g)}, {num(b)});')
        elif glsl_type == 'int':
            labels = ','.join(f'"{v}"' for v in p['values'].values())
            lines.append(f'uniform int u_sky_{name} : hint_enum({labels}) = {int(p["default"])};')
        else:
            lines.append(f'uniform float u_sky_{name} : hint_range({num(p["min"])}, {num(p["max"])}) = {num(p["default"])};')
    src = (
        HEADER + 'shader_type sky;\n\n'
        '// Shared 256x256 noise (tools/make_noise_texture.py). Import as data: lossless, no mipmaps.\n'
        'uniform sampler2D skyV1_noiseTexture : filter_linear, repeat_enable;\n'
        '// Engine TIME animates clouds, stars and aurora. Turn off to pin the sky at time_seconds\n'
        '// (a still sky avoids re-baking reflections every frame).\n'
        'uniform bool use_engine_time = true;\n'
        'uniform float time_seconds = 0.0;\n'
        + '\n'.join(lines) + '\n\n'
        '#define iTime (use_engine_time ? TIME : time_seconds)\n\n'
        + BODY +
        'void sky() {\n'
        '  // Godot: Y up, -Z forward. Sky space has north = +Z, so flip z.\n'
        '  COLOR = skyV1_radiance(normalize(vec3(EYEDIR.x, EYEDIR.y, -EYEDIR.z)));\n'
        '}\n'
    )
    out = ROOT / 'ports/godot/sky_match_v1.gdshader'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(src, encoding='utf8', newline='\n')
    print('wrote', out.relative_to(ROOT))


# ---- Unity 6 (Skybox shader, CG/HLSL) ---------------------------------------
def splat(src):
    """vecN(x) with one argument -> ((floatN)(x)); HLSL has no single-scalar vector constructor."""
    out, i = [], 0
    pattern = re.compile(r'\bvec([234])\(')
    while True:
        m = pattern.search(src, i)
        if not m:
            out.append(src[i:])
            return ''.join(out)
        out.append(src[i:m.start()])
        j, depth, comma = m.end(), 1, False
        while depth:
            ch = src[j]
            if ch in '([':
                depth += 1
            elif ch in ')]':
                depth -= 1
            elif ch == ',' and depth == 1:
                comma = True
            j += 1
        inner = splat(src[m.end():j - 1])
        out.append(f'float{m.group(1)}({inner})' if comma else f'((float{m.group(1)})({inner}))')
        i = j


def unity():
    s = BODY
    s = re.sub(r'\bpoint\b', 'pt', s)  # HLSL keyword
    s = re.sub(r'^const ', 'static const ', s, flags=re.M)
    s = splat(s)
    s = re.sub(r'\bvec([234])\b', r'float\1', s)
    for a, b in (('mix', 'lerp'), ('fract', 'frac')):
        s = re.sub(rf'\b{a}\(', b + '(', s)
    s = re.sub(r'\batan\(([^,()]+),', r'atan2(\1,', s)  # GLSL atan(y, x) == HLSL atan2(y, x)
    if re.search(r'\batan\(', s):
        raise SystemExit('unhandled atan( form')
    s = s.replace('textureLod(skyV1_noiseTexture,uv,0.0)', 'skyV1_sample(uv)')
    if 'textureLod' in s or re.search(r'\btexture\(', s):
        raise SystemExit('unhandled texture read')
    props, decl = [], []
    for glsl_type, name in UNIFORMS:
        p = PARAMS[name]
        label = p.get('label', name).replace('"', "'")
        if glsl_type == 'vec3':
            r, g, b = srgb(p['default'])
            props.append(f'        u_sky_{name} ("{label} ({name})", Color) = ({r:.6f}, {g:.6f}, {b:.6f}, 1)')
            decl.append(f'            float4 u_sky_{name};')
            s = re.sub(rf'\bu_sky_{name}\b', f'u_sky_{name}.rgb', s)
        elif glsl_type == 'int':
            props.append(f'        [IntRange] u_sky_{name} ("{label} ({name})", Range(0, {len(p["values"]) - 1})) = {int(p["default"])}')
            decl.append(f'            float u_sky_{name};')
            # Unity materials store floats; round once and use the int the sky expects.
            s = re.sub(rf'\bu_sky_{name}\b', f'((int)round(u_sky_{name}))', s)
        else:
            props.append(f'        u_sky_{name} ("{label} ({name})", Range({num(p["min"])}, {num(p["max"])})) = {num(p["default"])}')
            decl.append(f'            float u_sky_{name};')
    shader = f'''{HEADER}// Unity skybox (Built-in RP; Window > Rendering > Lighting > Skybox Material). Unity world is Y up,
// +Z forward, left-handed: the sky space as-is (north = +Z). Use a Linear colour space project so
// Color properties reach the shader as linear values.
Shader "Skybox/Sky Match v1"
{{
    Properties
    {{
        [NoScaleOffset] skyV1_noiseTexture ("Noise (data: sRGB off, no mipmaps, repeat, bilinear, no compression)", 2D) = "gray" {{}}
        [Toggle] use_engine_time ("Use engine time", Float) = 1
        time_seconds ("Time (s) when not using engine time", Float) = 0
        exposure ("Exposure (display, outside the sky)", Float) = 1
{chr(10).join(props)}
    }}
    SubShader
    {{
        Tags {{ "Queue"="Background" "RenderType"="Background" "PreviewType"="Skybox" }}
        Cull Off ZWrite Off
        Pass
        {{
            CGPROGRAM
            #pragma vertex vert
            #pragma fragment frag
            #pragma target 4.5
            #include "UnityCG.cginc"
            sampler2D skyV1_noiseTexture;
            float use_engine_time, time_seconds, exposure;
{chr(10).join(decl)}
            #define iTime (use_engine_time > 0.5 ? _Time.y : time_seconds)
            // GL convention: PNG row 0 at v = 0. Unity puts row 0 at v = 1, so flip V (Repeat makes -v == 1 - v).
            float4 skyV1_sample(float2 uv) {{ return tex2Dlod(skyV1_noiseTexture, float4(uv.x, -uv.y, 0.0, 0.0)); }}

{s}
            struct appdata {{ float4 vertex : POSITION; }};
            struct v2f {{ float4 pos : SV_POSITION; float3 dir : TEXCOORD0; }};
            v2f vert(appdata v) {{ v2f o; o.pos = UnityObjectToClipPos(v.vertex); o.dir = v.vertex.xyz; return o; }}
            float4 frag(v2f i) : SV_Target {{ return float4(skyV1_radiance(normalize(i.dir)) * exposure, 1.0); }}
            ENDCG
        }}
    }}
    Fallback Off
}}
'''
    out = ROOT / 'ports/unity/SkyMatchV1/SkyMatchV1.shader'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(shader, encoding='utf8', newline='\n')
    print('wrote', out.relative_to(ROOT))


def copy_noise():
    for folder in ('ports/godot', 'ports/unity/SkyMatchV1'):
        shutil.copyfile(ROOT / 'sky/textures/noise256.png', ROOT / folder / 'noise256.png')
        print('copied', folder + '/noise256.png')


if __name__ == '__main__':
    godot()
    unity()
    copy_noise()
